package com.project.w_3d_world.common.storage;

import com.project.w_3d_world.common.exception.ApiException;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.time.Duration;
import java.time.Instant;
import java.util.Base64;
import java.util.HexFormat;
import java.util.Map;
import java.util.TreeMap;
import java.util.UUID;
import java.util.stream.Collectors;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import tools.jackson.databind.ObjectMapper;

@Component
public class CloudinaryStorage {
    private final String cloudName;
    private final String apiKey;
    private final String apiSecret;
    private final ObjectMapper mapper;
    private final HttpClient client = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(10))
            .build();

    public CloudinaryStorage(
            @Value("${app.cloudinary.cloud-name}") String cloudName,
            @Value("${app.cloudinary.api-key}") String apiKey,
            @Value("${app.cloudinary.api-secret}") String apiSecret,
            ObjectMapper mapper) {
        this.cloudName = cloudName;
        this.apiKey = apiKey;
        this.apiSecret = apiSecret;
        this.mapper = mapper;
    }

    public UploadedImage uploadAvatar(int userId, byte[] bytes, String contentType) {
        return uploadImage("Avatar", "user_" + userId, bytes, contentType);
    }

    public UploadedImage uploadProduct(int productId, byte[] bytes, String contentType) {
        return uploadImage("Products", "product_" + productId, bytes, contentType);
    }

    public UploadedImage uploadRefund(int orderId, byte[] bytes, String contentType) {
        return uploadImage("Refund", "order_" + orderId, bytes, contentType);
    }

    private UploadedImage uploadImage(String folder, String prefix, byte[] bytes, String contentType) {
        var parameters = new TreeMap<String, String>();
        // folder supports fixed-folder accounts; asset_folder selects the Media Library
        // folder on dynamic-folder accounts. Public IDs are generated by the server.
        parameters.put("folder", folder);
        parameters.put("asset_folder", folder);
        parameters.put("public_id", prefix + "_" + UUID.randomUUID());
        parameters.put("overwrite", "false");
        parameters.put("timestamp", Long.toString(Instant.now().getEpochSecond()));
        var payload = signed(parameters);
        payload.put("file", "data:" + contentType + ";base64,"
                + Base64.getEncoder().encodeToString(bytes));
        Map<?, ?> response = post("upload", payload);
        String url = (String) response.get("secure_url");
        String publicId = (String) response.get("public_id");
        if (url == null || publicId == null || !url.startsWith("https://res.cloudinary.com/")) {
            throw storageError();
        }
        return new UploadedImage(url, publicId);
    }

    public void delete(String publicId) {
        if (publicId == null || publicId.isBlank()) {
            return;
        }
        post("destroy", signed(Map.of(
                "public_id", publicId,
                "invalidate", "true",
                "timestamp", Long.toString(Instant.now().getEpochSecond()))));
    }

    private TreeMap<String, String> signed(Map<String, String> parameters) {
        if (cloudName.isBlank() || apiKey.isBlank() || apiSecret.isBlank()) {
            throw new ApiException(HttpStatus.SERVICE_UNAVAILABLE, "Avatar storage is not configured.");
        }
        var payload = new TreeMap<>(parameters);
        String data = payload.entrySet().stream()
                .map(entry -> entry.getKey() + "=" + entry.getValue())
                .collect(Collectors.joining("&"));
        try {
            String signature = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256")
                    .digest((data + apiSecret).getBytes(StandardCharsets.UTF_8)));
            payload.put("signature", signature);
            payload.put("api_key", apiKey);
            return payload;
        } catch (Exception exception) {
            throw storageError();
        }
    }

    private Map<?, ?> post(String operation, Map<String, String> payload) {
        String body = payload.entrySet().stream()
                .map(entry -> encode(entry.getKey()) + "=" + encode(entry.getValue()))
                .collect(Collectors.joining("&"));
        HttpRequest request = HttpRequest.newBuilder(
                        URI.create("https://api.cloudinary.com/v1_1/" + cloudName + "/image/" + operation))
                .timeout(Duration.ofSeconds(30))
                .header("Content-Type", "application/x-www-form-urlencoded")
                .POST(HttpRequest.BodyPublishers.ofString(body))
                .build();
        try {
            var response = client.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() / 100 != 2) {
                throw storageError();
            }
            return mapper.readValue(response.body(), Map.class);
        } catch (InterruptedException exception) {
            Thread.currentThread().interrupt();
            throw storageError();
        } catch (Exception exception) {
            // Never expose provider payloads, credentials or signatures in API errors.
            throw storageError();
        }
    }

    private String encode(String value) {
        return URLEncoder.encode(value, StandardCharsets.UTF_8);
    }

    private ApiException storageError() {
        return new ApiException(HttpStatus.BAD_GATEWAY, "Avatar storage request failed. Please try again.");
    }

    public record UploadedImage(String url, String publicId) {}
}
